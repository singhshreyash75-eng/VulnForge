
"""Restricted HTTP client for the synthetic rate-limit lab.

The model cannot select an external origin, arbitrary method,
client identity, or unrestricted application endpoint.

Timing metadata is generated by the trusted tool implementation.
"""

import json
import math
import time

from typing import Literal
from urllib.parse import urlencode
from uuid import uuid4

import httpx
from pydantic import BaseModel, ConfigDict, Field


RATE_LIMIT_ORIGIN = "http://127.0.0.1:18082"


class RateLimitInspectInput(BaseModel):
    """Model-visible input for the registered rate-limit lab."""

    model_config = ConfigDict(extra="forbid")

    method: Literal["GET"] = "GET"

    path: Literal[
        "/health",
        "/api/search",
    ]

    query: str = Field(
        default="",
        max_length=100,
    )


class RestrictedRateLimitClient:
    """Bounded local inspection with stable client identity."""

    def __init__(
        self,
        max_requests: int = 20,
        timeout: float = 5.0,
        max_response_bytes: int = 8192,
        clock=None,
    ):
        if (
            type(max_requests) is not int
            or not 1 <= max_requests <= 20
        ):
            raise ValueError(
                "Request budget must be between 1 and 20"
            )

        if (
            isinstance(timeout, bool)
            or not isinstance(timeout, (int, float))
            or not math.isfinite(timeout)
            or timeout <= 0
        ):
            raise ValueError("Invalid timeout")

        if (
            type(max_response_bytes) is not int
            or not 1 <= max_response_bytes <= 65536
        ):
            raise ValueError("Invalid response size limit")

        self.origin = RATE_LIMIT_ORIGIN
        self.max_requests = max_requests
        self.timeout = timeout
        self.max_response_bytes = max_response_bytes

        self.request_count = 0
        self.client_identity = (
            f"vf-agent-{uuid4().hex}"
        )

        self._clock = clock or time.monotonic
        self._first_request_time = None

    async def inspect(
        self,
        args: RateLimitInspectInput,
    ) -> dict:
        """Execute one approved request and record timing."""

        if self.request_count >= self.max_requests:
            return {
                "error": "request_budget_exhausted"
            }

        if args.path == "/health" and args.query:
            return {
                "error": "query_not_allowed"
            }

        if args.path == "/api/search" and not args.query:
            return {
                "error": "query_required"
            }

        self.request_count += 1
        sequence = self.request_count

        query_string = (
            urlencode({"q": args.query})
            if args.path == "/api/search"
            else ""
        )

        recorded_path = args.path

        if query_string:
            recorded_path += "?" + query_string

        started = self._clock()

        if self._first_request_time is None:
            self._first_request_time = started

        relative_start = (
            started - self._first_request_time
        )

        headers = {}

        if args.path == "/api/search":
            headers["X-Lab-Client"] = (
                self.client_identity
            )

        try:
            async with httpx.AsyncClient(
                timeout=self.timeout,
                follow_redirects=False,
                trust_env=False,
            ) as client:

                async with client.stream(
                    args.method,
                    self.origin + recorded_path,
                    headers=headers,
                ) as response:

                    content = bytearray()

                    async for chunk in response.aiter_bytes():
                        remaining = (
                            self.max_response_bytes
                            - len(content)
                        )

                        if len(chunk) > remaining:
                            return {
                                "error": "response_too_large",
                                "status": response.status_code,
                            }

                        content.extend(chunk)

                    content_type = response.headers.get(
                        "content-type", ""
                    ).lower()

                    if "application/json" in content_type:
                        try:
                            body = json.loads(content)
                        except (
                            ValueError,
                            UnicodeDecodeError,
                        ):
                            body = content.decode(
                                "utf-8",
                                errors="replace",
                            )
                    else:
                        body = content.decode(
                            "utf-8",
                            errors="replace",
                        )

                    finished = self._clock()

                    return {
                        "method": args.method,
                        "path": recorded_path,
                        "identity": self.client_identity,
                        "status": response.status_code,
                        "body": body,
                        "request_sequence": sequence,
                        "request_started_seconds": round(
                            relative_start, 6
                        ),
                        "request_finished_seconds": round(
                            finished - self._first_request_time,
                            6,
                        ),
                    }

        except httpx.TimeoutException:
            return {
                "error": "request_timeout"
            }

        except httpx.RequestError:
            return {
                "error": "connection_failed"
            }
